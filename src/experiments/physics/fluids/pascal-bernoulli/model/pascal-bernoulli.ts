/**
 * Physical model for Pascal's Principle (Hydraulic Lift) and Bernoulli's Equation (Venturi Flow).
 * Pure TypeScript — no DOM, no Vue dependencies.
 */

export type ApparatusMode = 'venturi' | 'hydraulic';

export interface VenturiParams {
  apparatusMode: 'venturi';
  fluidDensity: number; // kg/m^3 (water: 1000, air: 1.2, oil: 850)
  inletVelocity: number; // v1 (m/s)
  inletDiameter: number; // D1 (m)
  constrictionDiameter: number; // D2 (m)
  inletPressure: number; // P1 (Pa)
  pipeLength: number; // m
  gravity: number; // m/s^2
  isRealMode: boolean;
}

export interface HydraulicParams {
  apparatusMode: 'hydraulic';
  fluidDensity: number; // kg/m^3
  piston1Radius: number; // r1 (m)
  piston2Radius: number; // r2 (m)
  inputForce: number; // F1 (N)
  inputDisplacement: number; // d1 (m)
  gravity: number; // m/s^2
  isRealMode: boolean;
}

export type PascalBernoulliParams = VenturiParams | HydraulicParams;

export interface FlowParticle {
  x: number; // normalized 0 to 1 along pipe
  offsetY: number; // normalized -0.8 to 0.8 across radius
  speedMultiplier: number;
}

export interface VenturiDerived {
  area1: number; // m^2
  area2: number; // m^2
  velocity1: number; // m/s
  velocity2: number; // m/s
  volumeFlowRate: number; // m^3/s
  pressure1: number; // Pa
  pressure2: number; // Pa
  deltaPressure: number; // Pa (P1 - P2)
  manometerHeight1: number; // m
  manometerHeight2: number; // m
  deltaHeight: number; // m
  dynamicPressure1: number; // 0.5 * rho * v1^2 (Pa)
  dynamicPressure2: number; // 0.5 * rho * v2^2 (Pa)
  frictionHeadLoss: number; // m (in real mode)
}

export interface HydraulicDerived {
  area1: number; // m^2
  area2: number; // m^2
  mechanicalAdvantage: number; // A2 / A1
  efficiency: number; // 1.0 (ideal) or ~0.92 (real)
  fluidPressure: number; // Pa (F1 / A1)
  outputForce: number; // N
  outputDisplacement: number; // m (d2 = d1 / MA)
  workInput: number; // J (F1 * d1)
  workOutput: number; // J (F2 * d2)
  liftedMass: number; // kg (F2 / g)
}

export interface PascalBernoulliState {
  t: number; // seconds
  venturi: VenturiDerived;
  hydraulic: HydraulicDerived;
  particles: FlowParticle[];
  // Animation state for hydraulic lift (0 to 1 progress of stroke)
  pistonProgress: number;
}

/**
 * Generate initial streamline tracer particles for the Venturi pipe flow.
 */
export function initParticles(count: number = 60): FlowParticle[] {
  const particles: FlowParticle[] = [];
  for (let i = 0; i < count; i++) {
    particles.push({
      x: Math.random(),
      offsetY: (Math.random() * 2 - 1) * 0.75,
      speedMultiplier: 0.9 + Math.random() * 0.2,
    });
  }
  return particles;
}

/**
 * Compute derived physical quantities for Venturi flow.
 */
export function computeVenturi(params: VenturiParams): VenturiDerived {
  const r1 = params.inletDiameter / 2;
  const r2 = params.constrictionDiameter / 2;
  const a1 = Math.PI * r1 * r1;
  const a2 = Math.PI * r2 * r2;

  const v1 = Math.max(0.01, params.inletVelocity);
  // Continuity: Q = A1 * v1 = A2 * v2
  const q = a1 * v1;
  const v2 = q / a2;

  const rho = params.fluidDensity;
  const dyn1 = 0.5 * rho * v1 * v1;
  const dyn2 = 0.5 * rho * v2 * v2;

  // Real mode friction / minor head loss in constriction
  // Minor loss coefficient K_L ~ 0.08
  const lossCoeff = params.isRealMode ? 0.08 : 0.0;
  const pressureLoss = lossCoeff * dyn2;
  const headLoss = pressureLoss / (rho * params.gravity);

  // Bernoulli: P1 + 0.5*rho*v1^2 = P2 + 0.5*rho*v2^2 + loss
  // P2 = P1 + 0.5*rho*(v1^2 - v2^2) - pressureLoss
  let p2 = params.inletPressure + (dyn1 - dyn2) - pressureLoss;
  // Guard against absolute negative pressure below cavitation / vacuum
  p2 = Math.max(100, p2);

  const deltaP = params.inletPressure - p2;

  // Manometer heights h = P / (rho * g)
  const h1 = params.inletPressure / (rho * params.gravity);
  const h2 = p2 / (rho * params.gravity);
  const deltaH = deltaP / (rho * params.gravity);

  return {
    area1: a1,
    area2: a2,
    velocity1: v1,
    velocity2: v2,
    volumeFlowRate: q,
    pressure1: params.inletPressure,
    pressure2: p2,
    deltaPressure: deltaP,
    manometerHeight1: h1,
    manometerHeight2: h2,
    deltaHeight: deltaH,
    dynamicPressure1: dyn1,
    dynamicPressure2: dyn2,
    frictionHeadLoss: headLoss,
  };
}

/**
 * Compute derived physical quantities for Hydraulic Lift.
 */
export function computeHydraulic(params: HydraulicParams): HydraulicDerived {
  const a1 = Math.PI * params.piston1Radius * params.piston1Radius;
  const a2 = Math.PI * params.piston2Radius * params.piston2Radius;

  const ma = a2 / a1;
  const efficiency = params.isRealMode ? 0.91 : 1.0;

  // Pressure generated by input force F1
  const p = params.inputForce / a1;

  // Output force F2 = F1 * (A2 / A1) * efficiency
  const f2 = params.inputForce * ma * efficiency;

  // Displacement conservation (incompressible fluid: A1 * d1 = A2 * d2)
  const d2 = params.inputDisplacement / ma;

  const w1 = params.inputForce * params.inputDisplacement;
  const w2 = f2 * d2;

  const liftedMass = f2 / params.gravity;

  return {
    area1: a1,
    area2: a2,
    mechanicalAdvantage: ma,
    efficiency,
    fluidPressure: p,
    outputForce: f2,
    outputDisplacement: d2,
    workInput: w1,
    workOutput: w2,
    liftedMass,
  };
}

/**
 * Initialize model state.
 */
export function createPascalBernoulliModel(
  vParams: VenturiParams,
  hParams: HydraulicParams,
): PascalBernoulliState {
  return {
    t: 0,
    venturi: computeVenturi(vParams),
    hydraulic: computeHydraulic(hParams),
    particles: initParticles(70),
    pistonProgress: 0,
  };
}

/**
 * Step the simulation forward by dt seconds.
 */
export function stepPascalBernoulliModel(
  state: PascalBernoulliState,
  params: PascalBernoulliParams,
  dt: number,
): PascalBernoulliState {
  const newT = state.t + dt;

  // Update derived values based on active mode
  let updatedVenturi = state.venturi;
  let updatedHydraulic = state.hydraulic;

  if (params.apparatusMode === 'venturi') {
    updatedVenturi = computeVenturi(params);
  } else {
    updatedHydraulic = computeHydraulic(params);
  }

  // Animate flow particles through Venturi pipe
  const newParticles = state.particles.map((p) => {
    // Local pipe diameter varies along x (0 to 1):
    // 0 to 0.35: D1 (inlet)
    // 0.35 to 0.50: taper down to D2
    // 0.50 to 0.65: throat at D2
    // 0.65 to 0.80: taper up to D1
    // 0.80 to 1.00: outlet at D1
    let localSpeedRatio = 1.0;
    const vRatio = updatedVenturi.velocity2 / updatedVenturi.velocity1;

    if (p.x >= 0.35 && p.x <= 0.65) {
      if (p.x < 0.5) {
        // Taper down
        const progress = (p.x - 0.35) / 0.15;
        localSpeedRatio = 1.0 + (vRatio - 1.0) * progress;
      } else {
        // Throat
        localSpeedRatio = vRatio;
      }
    } else if (p.x > 0.65 && p.x <= 0.8) {
      const progress = (p.x - 0.65) / 0.15;
      localSpeedRatio = vRatio - (vRatio - 1.0) * progress;
    } else {
      localSpeedRatio = 1.0;
    }

    // Advance particle horizontally
    // Normalize pipe velocity so particles cross smoothly
    const normalizedSpeed = 0.45 * (updatedVenturi.velocity1 / 2.0) * localSpeedRatio * p.speedMultiplier;
    let nextX = p.x + normalizedSpeed * dt;

    if (nextX > 1.05) {
      nextX = -0.05;
      return {
        x: nextX,
        offsetY: (Math.random() * 2 - 1) * 0.75,
        speedMultiplier: 0.9 + Math.random() * 0.2,
      };
    }

    return {
      ...p,
      x: nextX,
    };
  });

  // Animate hydraulic piston oscillation/cycling smoothly (stroke cycle of ~3.5 seconds)
  const cycleTime = 3.5;
  const cyclePhase = (newT % cycleTime) / cycleTime;
  // Sinusoidal stroke back and forth
  const pistonProgress = 0.5 * (1 - Math.cos(cyclePhase * 2 * Math.PI));

  return {
    t: newT,
    venturi: updatedVenturi,
    hydraulic: updatedHydraulic,
    particles: newParticles,
    pistonProgress,
  };
}
